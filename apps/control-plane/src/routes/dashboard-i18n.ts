export const DASHBOARD_TRANSLATIONS = { he, en, ar } as const;

export type DashboardI18nKey = keyof typeof en;

type KeysMatch<A, B> = keyof A extends keyof B
  ? keyof B extends keyof A
    ? true
    : never
  : never;

const _heEnMatch: KeysMatch<typeof he, typeof en> = true;
const _arEnMatch: KeysMatch<typeof ar, typeof en> = true;
void _heEnMatch;
void _arEnMatch;

export function dashboardI18nKeys(lang: DashboardI18nLang): readonly string[] {
  return Object.keys(DASHBOARD_TRANSLATIONS[lang]);
}

/** Object.keys is already unique; this checks he/en/ar expose the same set. */
export function dashboardI18nKeyMismatches(): readonly string[] {
  const enKeys = new Set(dashboardI18nKeys("en"));
  const mismatches: string[] = [];
  for (const lang of DASHBOARD_I18N_LANGS) {
    const keys = dashboardI18nKeys(lang);
    if (keys.length !== enKeys.size) {
      mismatches.push(`${lang}:count=${keys.length},en=${enKeys.size}`);
    }
    for (const key of keys) {
      if (!enKeys.has(key)) mismatches.push(`${lang}:extra:${key}`);
    }
    for (const key of enKeys) {
      if (!keys.includes(key)) mismatches.push(`${lang}:missing:${key}`);
    }
  }
  return mismatches;
}

/** Scan a JS/TS object-literal source block for duplicate property names. */
export function duplicateKeysInObjectLiteralSource(source: string): readonly string[] {
  const counts = new Map<string, number>();
  const re = /(?:^|,)\s*([A-Za-z_][A-Za-z0-9_]*)\s*:/g;
  let match: RegExpExecArray | null;
  while ((match = re.exec(source)) !== null) {
    const key = match[1]!;
    counts.set(key, (counts.get(key) ?? 0) + 1);
  }
  return [...counts.entries()].filter(([, n]) => n > 1).map(([key]) => key);
}
